"""Pre-record every line the web app speaks with a natural female neural voice.

Uses Kokoro-82M (Apache-2.0 model and voices, so the audio may be sold) through kokoro-onnx.

    pip install kokoro-onnx soundfile
    # model files: https://github.com/thewh1teagle/kokoro-onnx/releases (kokoro-v1.0.onnx, voices-v1.0.bin)
    NODE_PATH=$(npm root -g) node voice_catalog.js ../../pumpkin-patch-pals voice-lines.json
    python3 gen_voice.py <model dir> voice-lines.json ../../pumpkin-patch-pals/voice.js [voice] [speed]
"""
import base64
import hashlib
import json
import os
import subprocess
import sys
import tempfile

import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

model_dir, lines_path, out_path = sys.argv[1:4]
VOICE = sys.argv[4] if len(sys.argv) > 4 else "af_heart"
SPEED = float(sys.argv[5]) if len(sys.argv) > 5 else 0.92


def tidy(samples, sr):
    """Trim silence, pad, fade and level so every clip sounds consistent."""
    x = np.asarray(samples, dtype=np.float32)
    env = np.convolve(np.abs(x), np.ones(240) / 240, mode="same")
    on = np.where(env > 0.01)[0]
    if len(on):
        x = x[max(0, on[0] - int(0.03 * sr)): on[-1] + int(0.08 * sr)]
    x = np.concatenate([np.zeros(int(0.04 * sr), np.float32), x, np.zeros(int(0.06 * sr), np.float32)])
    fade = int(0.01 * sr)
    x[:fade] *= np.linspace(0, 1, fade)
    x[-fade:] *= np.linspace(1, 0, fade)
    rms = np.sqrt(np.mean(x ** 2)) or 1.0
    x *= min(0.1 / rms, 0.89 / (np.max(np.abs(x)) or 1.0))
    return x


def to_mp3(x, sr, tmp):
    wav, mp3 = os.path.join(tmp, "c.wav"), os.path.join(tmp, "c.mp3")
    sf.write(wav, x, sr)
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", wav, "-ac", "1", "-ar", "24000",
                    "-codec:a", "libmp3lame", "-b:a", "40k", mp3], check=True)
    with open(mp3, "rb") as f:
        return f.read()


if __name__ == "__main__":
    k = Kokoro(os.path.join(model_dir, "kokoro-v1.0.onnx"), os.path.join(model_dir, "voices-v1.0.bin"))
    lines = json.load(open(lines_path))
    clips, total = {}, 0
    tmp = tempfile.mkdtemp()
    cache = os.path.join(model_dir, "clip-cache")   # unchanged lines are reused, not re-recorded
    os.makedirs(cache, exist_ok=True)
    for i, ln in enumerate(lines):
        h = hashlib.sha1(f"{VOICE}|{SPEED}|{ln['tts']}".encode()).hexdigest()
        cp = os.path.join(cache, h + ".mp3")
        if os.path.exists(cp):
            data = open(cp, "rb").read()
        else:
            samples, sr = k.create(ln["tts"], voice=VOICE, speed=SPEED, lang="en-us")
            data = to_mp3(tidy(samples, sr), sr, tmp)
            open(cp, "wb").write(data)
        total += len(data)
        clips[ln["text"]] = "data:audio/mpeg;base64," + base64.b64encode(data).decode()
        if i % 50 == 0:
            print(f"{i}/{len(lines)}", flush=True)
    with open(out_path, "w") as f:
        f.write("// Generated by tpt-pumpkin-printables/tools/gen_voice.py - do not edit by hand.\n")
        f.write(f"// Voice: Kokoro-82M '{VOICE}' (Apache-2.0). {len(clips)} pre-recorded lines.\n")
        f.write("window.VOICE = " + json.dumps(clips, separators=(",", ":")) + ";\n")
    print(len(clips), "clips,", total // 1024, "KB audio,", os.path.getsize(out_path) // 1024, "KB voice.js")
